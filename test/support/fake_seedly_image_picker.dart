/// [SeedlyImagePicker] that returns [photo] (null mimics closing the
/// picker) or throws [error], without opening the system gallery.
class FakeSeedlyImagePicker implements SeedlyImagePicker {
  FakeSeedlyImagePicker({this.photo, this.error});

  Uint8List? photo;
  SeedlyImagePickerException? error;
  int calls = 0;

  @override
  Future<Uint8List?> pickFromGallery() async {
    calls++;
    if (error != null) throw error!;
    return photo;
  }
}
